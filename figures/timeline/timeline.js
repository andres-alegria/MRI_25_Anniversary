/* ---------------------------------------------------------------------------
   Treaty timeline - draws window.MRI_TIMELINE_DATA (generated by build_data.R)
   with the wording in window.MRI_TIMELINE_CONTENT (timeline-content.js).

   One block per new agreement, stacked by the year it was concluded:
   mountain-specific at the base, potentially relevant above, and the year's
   milestones (IPCC reports, UN resolutions, treaty decisions...) as coloured
   caps, read from Data_Additions_To_Timeline.xlsx via build_data.R. A collapsible panel
   underneath sorts the mountain-specific blocks into their families.

   Vanilla JS + SVG, no dependencies. Usage:
       MRITimeline.mount(document.getElementById('timeline'));
   The component sizes itself to its container and redraws on resize.
--------------------------------------------------------------------------- */
(function () {
  'use strict';

  const SVGNS = 'http://www.w3.org/2000/svg';

  // adjust chart geometry here (px)
  const GEO = {
    plotH: 200,          // height of the yearly columns
    plotHNarrow: 150,    // ... below 560 px wide
    narrowAt: 560,
    padL: 30, padR: 14,
    padT: 8,             // room above the tallest column (raise to ~30 if labelTracks is used)
    axisH: 26,           // year labels under the columns
    laneHead: 17,        // family name above each lane
    laneGap: 10,         // space between lanes
    gap: 2,              // surface gap between stacked blocks
    brickMaxW: 14,       // widest a block may get
    hitMin: 16,          // smallest hover target around a lane block
    tickMinPx: 44        // minimum spacing between year labels
  };

  function svg(tag, attrs, parent) {
    const n = document.createElementNS(SVGNS, tag);
    for (const k in attrs) n.setAttribute(k, attrs[k]);
    if (parent) parent.appendChild(n);
    return n;
  }
  function node(tag, cls, text, parent) {
    const n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text != null) n.textContent = text;   // untrusted strings only ever go in as text
    if (parent) parent.appendChild(n);
    return n;
  }
  function fmtDate(iso) {
    if (!iso) return null;
    const d = new Date(iso + 'T00:00:00');
    return isNaN(d) ? iso : d.toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
  }
  function clip(s, n) { return s.length > n ? s.slice(0, n - 1).trimEnd() + '…' : s; }

  function mount(root, opts) {
    const D = (opts && opts.data) || window.MRI_TIMELINE_DATA;
    const C = (opts && opts.content) || window.MRI_TIMELINE_CONTENT;
    const byId = new Map(D.treaties.map(t => [t.id, t]));
    const short = id => (C.short && C.short[id]) || byId.get(id).name;
    const treaties = D.treaties.filter(t => t.base);              // new agreements only, for now
    const maxYear = Math.max(new Date().getFullYear(), ...treaties.map(t => t.year), ...D.events.map(e => e.year));

    // One vertical scale for every view: the busiest year, its IPCC cap included
    const perYear = {};
    treaties.forEach(t => { perYear[t.year] = (perYear[t.year] || 0) + 1; });
    D.events.forEach(e => { perYear[e.year] = (perYear[e.year] || 0) + 1; });
    const maxN = Math.max(...Object.values(perYear));

    const state = { range: null };

    // ---- skeleton -----------------------------------------------------------
    root.innerHTML = '';
    const wrap = node('div', 'mtl', null, root);
    const controls = node('div', 'mtl-controls', null, wrap);
    controls.setAttribute('role', 'toolbar');
    const gRange = node('div', 'mtl-group', null, controls);
    gRange.setAttribute('aria-label', 'Time range');
    const legend = node('div', 'mtl-legend', null, wrap);
    node('div', 'mtl-unit', C.legend.unit, wrap);
    const chart = node('div', 'mtl-chart', null, wrap);
    const s = svg('svg', { role: 'group' }, chart);
    const lanesBox = node('details', 'mtl-lanes', null, chart);    // closed by default
    const lanesSum = node('summary', null, null, lanesBox);
    const ls = svg('svg', { role: 'group' }, lanesBox);
    lanesBox.addEventListener('toggle', () => render());
    const tip = node('div', 'mtl-tip', null, chart);
    tip.hidden = true;
    const table = node('details', 'mtl-table', null, wrap);
    node('div', 'mtl-source', C.source, wrap);

    function currentRange() {
      return state.range || (chart.clientWidth < GEO.narrowAt ? C.narrowRange : C.defaultRange);
    }
    function chips() {
      gRange.innerHTML = '';
      C.ranges.forEach(it => {
        const b = node('button', 'mtl-chip', it.label);
        b.type = 'button';
        b.setAttribute('aria-pressed', String(currentRange() === it.id));   // set before insertion: no fade-in
        b.addEventListener('click', () => { state.range = it.id; render(); });
        gRange.appendChild(b);
      });
    }

    // ---- tooltip ------------------------------------------------------------
    function place(px, py) {
      tip.hidden = false;
      const w = tip.offsetWidth, h = tip.offsetHeight;
      let x = px + 14, y = py + 14;
      if (x + w > chart.clientWidth) x = Math.max(0, px - w - 14);
      if (y + h > chart.clientHeight) y = Math.max(0, py - h - 14);
      tip.style.left = x + 'px';
      tip.style.top = y + 'px';
    }
    function row(parent, cls, strong, rest, labelFirst) {
      const r = node('div', 'row', null, parent);
      node('span', 'key ' + cls, null, r);
      const t = node('span', null, null, r);
      if (labelFirst) t.appendChild(document.createTextNode(rest + ' '));
      if (strong != null) node('b', null, strong, t);
      if (!labelFirst) t.appendChild(document.createTextNode(rest));
      return r;
    }
    function yearTip(year, list, events) {
      tip.innerHTML = '';
      node('div', 'h', String(year), tip);
      const l1 = list.filter(t => t.level === 'L1'), l2 = list.filter(t => t.level === 'L2');
      events.forEach(e => {                          // milestones: label first unless the title already holds it
        const lab = e.label || '', title = e.title || lab;
        const lead = lab && !lab.endsWith('…') && !title.includes(lab) ? lab : null;
        row(tip, 'ev-' + e.style, lead, (lead ? ' · ' : '') + clip(title, 90));
      });
      if (l1.length) {
        row(tip, 'l1', l1.length, ' ' + C.legend.L1.toLowerCase());
        const ul = node('ul', 'l1', null, tip);         // bullets are small blocks in the series colour
        l1.forEach(t => node('li', null, short(t.id), ul));
      }
      if (l2.length) {
        row(tip, 'l2', l2.length, ' ' + C.legend.L2.toLowerCase());
        const ul = node('ul', 'l2', null, tip);
        l2.slice(0, 4).forEach(t => node('li', null, clip(t.name, 70), ul));
        if (l2.length > 4) node('li', 'more', '+ ' + (l2.length - 4) + ' ' + C.tooltip.more, ul);
      }
    }
    function treatyTip(t) {
      tip.innerHTML = '';
      node('div', 'h', short(t.id), tip);
      if (short(t.id) !== t.name) node('div', 'sub', clip(t.name, 160), tip);
      row(tip, 'l1', fmtDate(t.signed) || t.year, C.tooltip.concluded, true);
      if (t.inForce) {
        row(tip, 'l1', fmtDate(t.inForce), C.tooltip.inForce, true);
        if (t.parties) row(tip, 'l1', t.parties, ' ' + C.tooltip.states);
      } else {
        row(tip, 'l1', null, C.tooltip.notInForce);
      }
      if (C.notes && C.notes[t.id]) node('div', 'note', C.notes[t.id], tip);
    }
    function hide() {
      tip.hidden = true;
      wrap.classList.remove('is-hover');
      wrap.querySelectorAll('.on').forEach(n => n.classList.remove('on'));
    }
    function highlight(sel) {                        // across the chart and the family panel
      wrap.classList.add('is-hover');
      wrap.querySelectorAll('.on').forEach(n => n.classList.remove('on'));
      wrap.querySelectorAll(sel).forEach(n => n.classList.add('on'));
    }
    function local(evt) {
      const r = chart.getBoundingClientRect();
      return [evt.clientX - r.left, evt.clientY - r.top];
    }
    function anchor(elm) {
      const r = elm.getBoundingClientRect(), c = chart.getBoundingClientRect();
      return [r.left - c.left + r.width / 2, r.top - c.top + r.height / 2];
    }
    document.addEventListener('pointerdown', e => { if (!chart.contains(e.target)) hide(); });

    // ---- draw ---------------------------------------------------------------
    function render() {
      const W = chart.clientWidth;
      if (!W) return;
      const narrow = W < GEO.narrowAt;
      const range = C.ranges.find(r => r.id === currentRange()) || C.ranges[0];
      const from = range.from, to = maxYear;
      chips();

      const vis = treaties.filter(t => t.year >= from && t.year <= to);
      const events = D.events.filter(e => e.year >= from && e.year <= to);

      // legend
      legend.innerHTML = '';
      const nL1 = vis.filter(t => t.level === 'L1').length, nL2 = vis.length - nL1;
      const keys = [];                               // the key is read from the data, ordered by stack_rank
      D.events.forEach(e => { if (!keys.some(k => k.key === e.key)) keys.push(e); });
      keys.sort((a, b) => a.rank - b.rank);
      [['l1', C.legend.L1, nL1], ['l2', C.legend.L2, nL2],
       ...keys.map(k => ['ev-' + k.style, (C.keys && C.keys[k.key]) || k.key, events.filter(e => e.key === k.key).length])
      ].forEach(([c, label, n]) => {
        const k = node('span', 'mtl-key', null, legend);
        node('span', 'mtl-swatch ' + c, null, k);
        k.appendChild(document.createTextNode(label));   // counts stay in the tooltips and the table
      });

      // scales
      const plotH = narrow ? GEO.plotHNarrow : GEO.plotH;
      const L = GEO.padL, R = W - GEO.padR, cw = (R - L) / (to - from + 1);
      const x = y => L + (y - from + 0.5) * cw;
      const baseY = GEO.padT + plotH;
      const unit = plotH / maxN;
      const bw = cw >= 4 ? Math.min(cw - GEO.gap, GEO.brickMaxW) : Math.max(cw - 0.6, 1);
      const bh = Math.max(unit - GEO.gap, 1.5);
      const rx = Math.min(1.5, bw / 3);
      const H = baseY + GEO.axisH;

      s.innerHTML = '';
      s.setAttribute('viewBox', `0 0 ${W} ${H}`);
      s.setAttribute('height', H);
      s.setAttribute('aria-label',
        `${vis.length} new multilateral environmental agreements, ${from}–${to}: ${nL1} ${C.legend.L1.toLowerCase()}, ` +
        `${nL2} ${C.legend.L2.toLowerCase()}, with ${events.length} ${C.legend.milestones}. Details in the table below.`);

      // gridlines + y labels
      const grid = svg('g', { class: 'grid tick' }, s);
      for (let v = 10; v <= maxN; v += 10) {
        const gy = baseY - v * unit;
        svg('line', { x1: L, x2: R, y1: gy, y2: gy }, grid);
        const t = svg('text', { x: L - 6, y: gy + 4, 'text-anchor': 'end' }, grid);
        t.textContent = v;
      }

      // yearly columns: mountain-specific at the base, the rest above, then the
      // year's milestones in stack_rank order (decisions, assessments, Assembly)
      const byYear = new Map();
      vis.forEach(t => { if (!byYear.has(t.year)) byYear.set(t.year, []); byYear.get(t.year).push(t); });
      events.forEach(e => { if (!byYear.has(e.year)) byYear.set(e.year, []); });
      const gCols = svg('g', {}, s), gLabels = svg('g', {}, s), gHits = svg('g', {}, s);
      const placed = [];                                             // cap label boxes
      const stackOf = y => (byYear.has(y) ? byYear.get(y).length : 0) + events.filter(e => e.year === y).length;
      byYear.forEach((list, year) => {
        list.sort((a, b) => (a.level === b.level ? (a.signed || '').localeCompare(b.signed || '') : a.level < b.level ? -1 : 1));
        const brick = (i, cls, extra) => svg('rect', Object.assign({
          class: 'brick ' + cls, 'data-year': year,
          x: x(year) - bw / 2, y: baseY - (i + 1) * unit + GEO.gap / 2, width: bw, height: bh, rx
        }, extra), gCols);
        list.forEach((t, i) => brick(i, t.level.toLowerCase(), { 'data-id': t.id }));
        const evs = events.filter(e => e.year === year);
        evs.forEach((e, k) => {
          const i = list.length + k;
          const hollow = /_hollow$/.test(e.style), inset = hollow ? 0.75 : 0;   // outlined variants stay inside the block
          brick(i, 'ev ev-' + e.style, { 'data-ev': e.id,
            x: x(year) - bw / 2 + inset, y: baseY - (i + 1) * unit + GEO.gap / 2 + inset,
            width: Math.max(bw - 2 * inset, 1), height: Math.max(bh - 2 * inset, 1) });
          if (!(C.labelTracks || []).includes(e.track)) return;     // only the labelled tracks get text
          // label in clear sky above every column it spans, with a leader down to
          // its cap; nudged up when it would touch another label, else hover only
          const lab = svg('text', { class: 'cap-label', x: x(year), y: 0, 'text-anchor': 'middle' }, gLabels);
          lab.textContent = e.label;
          const w = lab.getComputedTextLength() || e.label.length * 6;
          const capTop = baseY - (i + 1) * unit + GEO.gap / 2;
          let tallest = i + 1;
          for (let y = Math.floor(from + (x(year) - w / 2 - L) / cw); y <= from + (x(year) + w / 2 - L) / cw; y++)
            tallest = Math.max(tallest, stackOf(y));
          let ly = baseY - tallest * unit - 4, ok = false;
          for (let tries = 0; tries < 3 && ly > 10; tries++, ly -= 12) {
            const box = [x(year) - w / 2 - 2, ly - 10, x(year) + w / 2 + 2, ly + 2];
            if (!placed.some(p => box[0] < p[2] && box[2] > p[0] && box[1] < p[3] && box[3] > p[1])) {
              placed.push(box); ok = true; break;
            }
          }
          if (!ok) { lab.remove(); return; }
          lab.setAttribute('y', ly);
          if (capTop - ly > 8) svg('line', { class: 'cap-leader', x1: x(year), x2: x(year), y1: ly + 3, y2: capTop - 1 }, gLabels);
        });
        const hit = svg('rect', { class: 'col-hit', x: x(year) - cw / 2, y: 0, width: cw, height: baseY + 6 }, gHits);
        const show = evt => { yearTip(year, list, evs); highlight(`[data-year="${year}"]`); place(...local(evt)); };
        hit.addEventListener('pointerenter', show);
        hit.addEventListener('pointermove', evt => place(...local(evt)));
        hit.addEventListener('pointerleave', hide);
      });
      svg('line', { class: 'baseline', x1: L, x2: R, y1: baseY, y2: baseY }, s);

      // year axis
      const steps = [1, 2, 5, 10, 20, 25, 50];
      const step = steps.find(st => st * cw >= GEO.tickMinPx) || 50;
      const ax = svg('g', { class: 'tick' }, s);
      for (let y = Math.ceil(from / step) * step; y <= to; y += step) {
        svg('line', { class: 'baseline', x1: x(y), x2: x(y), y1: baseY, y2: baseY + 4 }, ax);
        const t = svg('text', { x: x(y), y: baseY + 17, 'text-anchor': 'middle' }, ax);
        t.textContent = y;
      }

      // ---- family panel: the mountain-specific blocks again, one lane per family
      const listed = new Set(C.families.flatMap(f => f.ids));
      const fams = C.families.map(f => ({ label: f.label, items: f.ids.map(id => byId.get(id)) }));
      treaties.filter(t => t.level === 'L1' && !listed.has(t.id)).forEach(t => fams.push({ label: short(t.id), items: [t] }));
      const lanes = fams.map(f => ({ label: f.label, items: f.items.filter(t => t && t.level === 'L1' && vis.includes(t)) }))
        .filter(f => f.items.length);
      lanesSum.textContent = C.lanesSummary;
      ls.innerHTML = '';
      if (lanesBox.open) {
        let top = 6;
        lanes.forEach(lane => {
          const stack = {};
          lane.items.forEach(t => { stack[t.year] = (stack[t.year] || 0) + 1; });
          const depth = Math.max(...Object.values(stack));
          const laneBase = top + GEO.laneHead + depth * unit;
          const g = svg('g', {}, ls);
          const years = lane.items.map(t => t.year), x0 = x(Math.min(...years)), x1 = x(Math.max(...years));
          svg('line', { class: 'lane-line', x1: x0 - bw / 2, x2: x1 + bw / 2, y1: laneBase + 1.5, y2: laneBase + 1.5 }, g);
          const label = svg('text', { class: 'lane-label', x: x0 - bw / 2, y: top + 11 }, g);
          label.textContent = lane.label + '  ';
          const n = svg('tspan', { class: 'n' }, label);
          n.textContent = lane.items.length;
          const lw = label.getComputedTextLength() || (lane.label.length + 4) * 6.4;
          label.setAttribute('x', Math.max(L, Math.min(x0 - bw / 2, R - lw)));
          const seen = {};
          lane.items.forEach(t => {
            const k = seen[t.year] = (seen[t.year] || 0) + 1;
            const by = laneBase - k * unit + GEO.gap / 2;
            svg('rect', { class: 'brick l1', 'data-id': t.id, 'data-year': t.year,
              x: x(t.year) - bw / 2, y: by, width: bw, height: bh, rx }, g);
            const hw = Math.max(bw, GEO.hitMin), hh = Math.max(unit, GEO.hitMin);
            const hit = svg('rect', { class: 'lane-hit', x: x(t.year) - hw / 2, y: by + bh / 2 - hh / 2, width: hw, height: hh,
              tabindex: 0, 'aria-label': `${short(t.id)}, ${t.year}` }, g);
            const show = pt => { treatyTip(t); highlight(`[data-id="${t.id}"]`); place(...pt); };
            hit.addEventListener('pointerenter', evt => show(local(evt)));
            hit.addEventListener('pointerleave', hide);
            hit.addEventListener('focus', () => show(anchor(hit)));
            hit.addEventListener('blur', hide);
          });
          top = laneBase + GEO.laneGap;
        });
        ls.setAttribute('viewBox', `0 0 ${W} ${top}`);
        ls.setAttribute('height', top);
      }

      // table view (every mountain-specific agreement)
      const all1 = treaties.filter(t => t.level === 'L1');
      const open = table.open;
      table.innerHTML = '';
      table.open = open;
      node('summary', null, C.tableSummary, table);
      const tb = node('table', null, null, table);
      const hr = node('tr', null, null, node('thead', null, null, tb));
      ['Year', 'Agreement', C.tooltip.inForce, 'States'].forEach(h => node('th', null, h, hr));
      const body = node('tbody', null, null, tb);
      all1.forEach(t => {
        const r = node('tr', null, null, body);
        node('td', 'num', t.year, r);
        node('td', null, short(t.id), r);
        node('td', 'num', fmtDate(t.inForce) || C.tooltip.notInForce, r);
        node('td', 'num', t.inForce && t.parties ? t.parties : '–', r);
      });
    }

    // Redraw on width changes only, and in the next frame: a redraw changes the
    // chart's height, and doing that inside the observer's own callback trips
    // the browser's "ResizeObserver loop" error.
    let lastW = chart.clientWidth, queued = 0;
    new ResizeObserver(() => {
      if (queued) return;
      queued = requestAnimationFrame(() => {
        queued = 0;
        if (chart.clientWidth !== lastW) { lastW = chart.clientWidth; render(); }
      });
    }).observe(chart);
    render();
    return { render };
  }

  window.MRITimeline = { mount };
})();
