/* ---------------------------------------------------------------------------
   Glacier mass change - draws window.MRI_GLACIERS_DATA (generated by
   build_data.R) with the wording in window.MRI_GLACIERS_CONTENT.

   The default view stacks the years into a descending staircase: each block
   is one hydrological year, hanging from where the last one ended, so the
   column's length is that year's loss and its position the loss so far - the
   counterform of the treaty timeline's rising stack in Figure 1. A second
   view spreads the same years along a zero baseline with their 1-sigma
   whiskers. A collapsible panel underneath gives each glacier region its own
   lane: cumulative thinning in m w.e., all lanes on one scale.

   Vanilla JS + SVG, no dependencies. Usage:
       MRIGlaciers.mount(document.getElementById('glaciers'));
   The component sizes itself to its container and redraws on resize.
--------------------------------------------------------------------------- */
(function () {
  'use strict';

  const SVGNS = 'http://www.w3.org/2000/svg';

  // adjust chart geometry here (px)
  const GEO = {
    plotH: 330,          // height of the staircase plot
    plotHNarrow: 230,    // ... below 560 px wide
    narrowAt: 560,
    padL: 62, padR: 14,
    padT: 18,            // room above the zero line
    gainsRoom: 40,       // ... plus this above the plot (not on phones), where the scale figure's foot tucks in
    axisH: 26,           // year labels under the plot
    gap: 2,              // surface gap between neighbouring year columns
    brickMaxW: 14,       // widest a year column may get
    tickMinPx: 44,       // minimum spacing between year labels
    laneHead: 16,        // region name above each lane
    laneSpark: 38,       // height of a lane's area chart
    laneGap: 13,         // space between lanes
    keySize: 44,         // the big number, cumulative view (adjust size here)
    keySizeNarrow: 26,
    // the Map tab (adjust dot sizes here, px on screen)
    mapRMax: 9, mapRMaxNarrow: 6,       // the cell with the most glacier area
    mapRMin: 1.1,                        // the smallest cells
    surveyR: 1.3,                        // a GlaThiDa survey site
    // the scale figure (1 km cube + Eiffel Tower), top right (adjust size here)
    scaleW: 190, scaleH: 178,            // canvas, px
    scaleWNarrow: 128, scaleHNarrow: 128,
    scaleLabels: 32, scaleLabelsNarrow: 28,   // room under the scene for its labels
    scaleFont: 11, scaleFontNarrow: 10,   // label size, px
    scaleGround: 0.05,                    // tint of the ground under cube and tower (0 = none)
    scaleGrid: 0.12                       // strength of the 100 m grid on the cube (0 = none)
  };

  const MINUS = '−', NBSP = ' ';   // real minus sign, narrow space

  function svg(tag, attrs, parent) {
    const n = document.createElementNS(SVGNS, tag);
    for (const k in attrs) n.setAttribute(k, attrs[k]);
    if (parent) parent.appendChild(n);
    return n;
  }
  function node(tag, cls, text, parent) {
    const n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text != null) n.textContent = text;
    if (parent) parent.appendChild(n);
    return n;
  }
  // 1234.5 -> "1 234.5" with a narrow space; negative numbers get a true minus
  function fmt(v, dec) {
    const s = Math.abs(v).toFixed(dec || 0).replace(/\B(?=(\d{3})+(?!\d))/g, NBSP);
    return (v < 0 ? MINUS : '') + s;
  }
  function signed(v, dec) { return (v > 0 ? '+' : '') + fmt(v, dec); }
  function fill(template, vals) {
    return template.replace(/\{(\w+)\}/g, (m, k) => (k in vals ? vals[k] : m));
  }
  function rgb(css) {                          // any CSS colour -> [r, g, b], 0-255
    const c = document.createElement('canvas').getContext('2d');
    c.fillStyle = '#000'; c.fillStyle = css; c.fillRect(0, 0, 1, 1);
    const d = c.getImageData(0, 0, 1, 1).data;
    return [d[0], d[1], d[2]];
  }
  // smooth curve through (xs, ys) that never overshoots (Fritsch-Carlson);
  // clamps outside the range
  function monotone(xs, ys) {
    const n = xs.length, d = [], m = [];
    for (let k = 0; k < n - 1; k++) d.push((ys[k + 1] - ys[k]) / (xs[k + 1] - xs[k]));
    m[0] = d[0]; m[n - 1] = d[n - 2];
    for (let k = 1; k < n - 1; k++) m[k] = d[k - 1] * d[k] <= 0 ? 0 : (d[k - 1] + d[k]) / 2;
    for (let k = 0; k < n - 1; k++) {
      if (!d[k]) { m[k] = m[k + 1] = 0; continue; }
      const a = m[k] / d[k], b = m[k + 1] / d[k], s = a * a + b * b;
      if (s > 9) { const t = 3 / Math.sqrt(s); m[k] = t * a * d[k]; m[k + 1] = t * b * d[k]; }
    }
    return x => {
      let k = 0;
      while (k < n - 2 && x > xs[k + 1]) k++;
      const h = xs[k + 1] - xs[k], t = Math.min(1, Math.max(0, (x - xs[k]) / h)), t2 = t * t, t3 = t2 * t;
      return (2 * t3 - 3 * t2 + 1) * ys[k] + (t3 - 2 * t2 + t) * h * m[k] +
             (-2 * t3 + 3 * t2) * ys[k + 1] + (t3 - t2) * h * m[k + 1];
    };
  }

  // ---- scale figure: a gigatonne of water beside the Eiffel Tower ----------
  // 1 Gt of water fills a cube 1 km on each side. The cube and the tower
  // (modelled from S.dims) share one fixed orthographic view, drawn on a
  // canvas the way the site's mountain globe is: shaded faces, thin lines, the
  // same tilt. It does not move; it is redrawn only when the size, the theme
  // or the fonts change.
  function scaleFigure(host, S, wrap) {
    const cv = document.createElement('canvas');
    cv.setAttribute('role', 'img');
    cv.setAttribute('aria-label', S.label);
    host.appendChild(cv);
    const ctx = cv.getContext('2d');
    const T = S.dims, E = 1000, H = E / 2;           // cube edge and half edge, m
    const half = T.base / 2, fl = T.floors;
    const TX = -H - S.gap - half, TY = H - half;      // tower centre: beside the cube's left face

    // tower profile by height: half-width of the outer envelope (through the
    // published base and platform sizes) and of the opening between the legs,
    // which closes at the second floor
    const outer = monotone([0, fl[0][0], fl[1][0], fl[2][0]], [half, fl[0][1] / 2, fl[1][1] / 2, fl[2][1] / 2]);
    const inner = monotone([0, fl[0][0], fl[1][0]], [half - T.leg, fl[0][1] / 4, 0]);

    // ---- geometry, built once: polygons with outward normals, and lines ------
    const newell = p => {                          // unit normal of a polygon (0 if degenerate)
      let x = 0, y = 0, z = 0;
      for (let a = 0; a < p.length; a++) {
        const u = p[a], v = p[(a + 1) % p.length];
        x += (u[1] - v[1]) * (u[2] + v[2]); y += (u[2] - v[2]) * (u[0] + v[0]); z += (u[0] - v[0]) * (u[1] + v[1]);
      }
      const l = Math.hypot(x, y, z);
      return l ? [x / l, y / l, z / l] : [0, 0, 0];
    };
    const tower = [];                              // drawn layer by layer, bottom up
    // the tower is turned on its site to face the eye at rest, so the arches
    // between its legs show (seen corner-on, the legs hide one another)
    const turn = -S.view * Math.PI / 180, tc = Math.cos(turn), ts = Math.sin(turn);
    const at = p => [TX + p[0] * tc - p[1] * ts, TY + p[0] * ts + p[1] * tc, p[2]];
    function quad(layer, pts, hint) {
      pts = pts.map(at);
      const n = newell(pts);
      if (n[0] * hint[0] + n[1] * hint[1] + n[2] * hint[2] < 0) n.forEach((v, i) => { n[i] = -v; });
      tower.push({ layer, pts, n });
    }
    // the four sides of a box whose extent f(z) = [xmin, xmax, ymin, ymax] changes with height
    function ring(layer, f, z0, z1, steps) {
      for (let s = 0; s < steps; s++) {
        const za = z0 + (z1 - z0) * s / steps, zb = z0 + (z1 - z0) * (s + 1) / steps, a = f(za), b = f(zb);
        quad(layer, [[a[0], a[2], za], [a[0], a[3], za], [b[0], b[3], zb], [b[0], b[2], zb]], [-1, 0, 0]);
        quad(layer, [[a[1], a[2], za], [a[1], a[3], za], [b[1], b[3], zb], [b[1], b[2], zb]], [1, 0, 0]);
        quad(layer, [[a[0], a[2], za], [a[1], a[2], za], [b[1], b[2], zb], [b[0], b[2], zb]], [0, -1, 0]);
        quad(layer, [[a[0], a[3], za], [a[1], a[3], za], [b[1], b[3], zb], [b[0], b[3], zb]], [0, 1, 0]);
      }
    }
    const cap = (layer, f, z) => { const a = f(z); quad(layer, [[a[0], a[2], z], [a[1], a[2], z], [a[1], a[3], z], [a[0], a[3], z]], [0, 0, 1]); };
    const env = over => z => { const o = outer(z) + over; return [-o, o, -o, o]; };
    const leg = (sx, sy) => z => {
      const o = outer(z), i = Math.max(0, inner(z)), xs = [sx * i, sx * o].sort((p, q) => p - q),
            ys = [sy * i, sy * o].sort((p, q) => p - q);
      return [xs[0], xs[1], ys[0], ys[1]];
    };
    const legs = (layer, z0, z1, steps) => [[-1, -1], [1, -1], [1, 1], [-1, 1]]
      .forEach(([sx, sy]) => ring(layer, leg(sx, sy), z0, z1, steps));
    const b1 = fl[0][0] - 11.6, b2 = fl[1][0] - 5, top3 = fl[2][0] + 3;    // girder bands under the floors (drawn)
    legs(0, 0, b1, 6);
    // the four arches between the legs, under the first floor
    for (let side = 0; side < 4; side++) {
      const line = [], zs = 10, rot = side * Math.PI / 2, c = Math.cos(rot), s = Math.sin(rot);
      for (let t = 0; t <= 16; t++) {
        const a = Math.PI * t / 16, z = zs + (b1 - zs) * Math.sin(a), u = inner(zs) * Math.cos(a), w = -outer(z) - 0.5;
        line.push(at([u * c - w * s, u * s + w * c, z]));
      }
      tower.push({ layer: 0, line, n: [-s, -c, 0] });
    }
    ring(1, env(0.8), b1, fl[0][0], 2); cap(1, env(0.8), fl[0][0]);
    legs(2, fl[0][0], b2, 6);
    ring(3, env(0.6), b2, fl[1][0], 1); cap(3, env(0.6), fl[1][0]);
    ring(4, env(0), fl[1][0], fl[2][0], 8);
    const plat = () => { const o = fl[2][1] / 2 + 0.5; return [-o, o, -o, o]; };
    ring(5, plat, fl[2][0], top3, 1); cap(5, plat, top3);
    const lantern = z => { const o = 4 - 1.5 * (z - top3) / (T.top - top3); return [-o, o, -o, o]; };
    ring(6, lantern, top3, T.top, 1); cap(6, lantern, T.top);
    tower.push({ layer: 7, line: [at([0, 0, T.top]), at([0, 0, T.tip])], n: null });   // antenna
    const layers = Math.max(...tower.map(p => p.layer)) + 1;

    // the cube: each face as origin + two edge vectors, with its outward normal
    const cube = [
      { o: [-H, -H, E], u: [E, 0, 0], v: [0, E, 0], n: [0, 0, 1] },
      { o: [-H, -H, 0], u: [0, E, 0], v: [0, 0, E], n: [-1, 0, 0] },
      { o: [H, -H, 0], u: [0, E, 0], v: [0, 0, E], n: [1, 0, 0] },
      { o: [-H, -H, 0], u: [E, 0, 0], v: [0, 0, E], n: [0, -1, 0], front: true },   // carries "1 Gt" and "1 km"
      { o: [-H, H, 0], u: [E, 0, 0], v: [0, 0, E], n: [0, 1, 0] }
    ];
    const fp = (f, a, b) => [0, 1, 2].map(i => f.o[i] + a * f.u[i] + b * f.v[i]);

    // the view: turned S.view degrees about the middle of the two footprints,
    // the eye S.tilt degrees above the ground; the scene's extent in that
    // view (in metres) sets the scale that fills the canvas
    const PX = (TX - half + H) / 2, PY = 0;
    const psi = S.view * Math.PI / 180, cp = Math.cos(psi), sp = Math.sin(psi);
    const tilt = S.tilt * Math.PI / 180, cf = Math.cos(tilt), sf = Math.sin(tilt);
    const flat = q => {                            // world (m) -> [right, up] in metres, before scaling
      const X = q[0] - PX, Y = q[1] - PY;
      return [X * cp - Y * sp, q[2] * cf + (X * sp + Y * cp) * sf];
    };
    const probe = [];
    [-H, H].forEach(x => [-H, H].forEach(y => { probe.push([x, y, 0], [x, y, E]); }));
    [-half, half].forEach(x => [-half, half].forEach(y => probe.push(at([x, y, 0]))));
    probe.push(at([0, 0, T.tip]));
    const ext = probe.map(flat);
    const left = Math.min(...ext.map(p => p[0])), right = Math.max(...ext.map(p => p[0]));
    const up = Math.max(...ext.map(p => p[1])), down = Math.min(...ext.map(p => p[1]));

    // light from the upper right, a little towards the viewer (camera frame:
    // right, up, towards the viewer); 0.5 = the colour as set in the CSS
    const L = (v => { const l = Math.hypot(...v); return v.map(x => x / l); })([0.25, 0.65, 0.72]);
    const LIFT = 0.6, DROP = 0.6;                  // adjust face contrast here
    const shade = (c, b) => {
      const t = Math.max(-1, Math.min(1, (b - 0.5) * 2));
      return 'rgb(' + c.map(v => Math.round(t > 0 ? v + (255 - v) * t * LIFT : v * (1 + t * DROP))).join(',') + ')';
    };
    const lum = c => {
      const f = v => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); };
      return 0.2126 * f(c[0]) + 0.7152 * f(c[1]) + 0.0722 * f(c[2]);
    };
    const contrast = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };

    let col = {}, W = 0, Hc = 0, k = 1, cx = 0, cy = 0, dpr = 1, narrow = false;   // canvas size and scale (px per m)
    function readColors() {                        // colours come from CSS tokens, so the theme switch follows
      const cs = getComputedStyle(wrap), v = n => cs.getPropertyValue(n).trim();
      col = { ice: rgb(v('--mgl-ice')), ink: rgb(v('--mgl-text')), surface: rgb(v('--mgl-surface')),
              text: v('--mgl-text'), dim: v('--mgl-dim'), font: v('--mgl-font') || 'Jost, sans-serif' };
      col.surfaceCss = 'rgb(' + col.surface.join(',') + ')';
    }

    function draw() {
      if (!W) return;
      const P = q => {                             // world (m) -> [x px, y px, depth: larger is nearer]
        const X = q[0] - PX, Y = q[1] - PY, yr = X * sp + Y * cp;
        return [cx + k * (X * cp - Y * sp), cy - k * (q[2] * cf + yr * sf), -yr * cf + q[2] * sf];
      };
      const Ncam = n => {                          // world normal -> camera frame
        const xr = n[0] * cp - n[1] * sp, yr = n[0] * sp + n[1] * cp;
        return [xr, n[2] * cf + yr * sf, -yr * cf + n[2] * sf];
      };
      const bright = n => { const c = Ncam(n); return [0.28 + 0.72 * Math.max(0, c[0] * L[0] + c[1] * L[1] + c[2] * L[2]), c[2]]; };
      const poly = (pts, fillCss) => {
        ctx.beginPath();
        pts.forEach((q, i) => { const s = P(q); i ? ctx.lineTo(s[0], s[1]) : ctx.moveTo(s[0], s[1]); });
        ctx.closePath(); ctx.fillStyle = fillCss; ctx.fill();
        ctx.strokeStyle = fillCss; ctx.lineWidth = 0.5; ctx.stroke();      // closes hairline seams between faces
      };

      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      ctx.clearRect(0, 0, W, Hc);

      // ground under both, a faint tint
      if (GEO.scaleGround) {
        const m = 110;
        ctx.globalAlpha = GEO.scaleGround;
        poly([[TX - half - m, -H - m, 0], [H + m, -H - m, 0], [H + m, H + m, 0], [TX - half - m, H + m, 0]], col.text);
        ctx.globalAlpha = 1;
      }

      function drawCube() {
        cube.forEach(f => {
          const [b, toward] = bright(f.n);
          if (toward <= 0.001) return;
          const c = shade(col.ice, b);
          poly([fp(f, 0, 0), fp(f, 1, 0), fp(f, 1, 1), fp(f, 0, 1)], c);
          // 100 m grid, so the tower can be read against the face (adjust grid tint here)
          ctx.beginPath();
          for (let j = 1; j < 10; j++) {
            let a = P(fp(f, j / 10, 0)), z = P(fp(f, j / 10, 1));
            ctx.moveTo(a[0], a[1]); ctx.lineTo(z[0], z[1]);
            a = P(fp(f, 0, j / 10)); z = P(fp(f, 1, j / 10));
            ctx.moveTo(a[0], a[1]); ctx.lineTo(z[0], z[1]);
          }
          ctx.strokeStyle = col.surfaceCss; ctx.globalAlpha = GEO.scaleGrid; ctx.lineWidth = 0.6; ctx.stroke();
          ctx.globalAlpha = 1;
          if (f.front) {                           // "1 Gt", painted on the face
            const o = P(fp(f, 0.5, 0.5)), face = rgb(c);
            const ink = contrast(face, col.surface) >= contrast(face, col.ink) ? col.surfaceCss : col.text;
            ctx.save();
            ctx.setTransform(k * cp * dpr, -k * sp * sf * dpr, 0, k * cf * dpr, o[0] * dpr, o[1] * dpr);
            ctx.font = '600 300px ' + col.font;    // in metres on the face (adjust size here)
            ctx.textAlign = 'center'; ctx.textBaseline = 'middle';
            ctx.fillStyle = ink; ctx.fillText(S.face, 0, 10);
            ctx.restore();
          }
        });
        // edges of the visible faces, a lighter line (adjust edge colour here)
        ctx.beginPath();
        cube.forEach(f => {
          if (Ncam(f.n)[2] <= 0.001) return;
          [fp(f, 0, 0), fp(f, 1, 0), fp(f, 1, 1), fp(f, 0, 1)].map(P)
            .forEach((s, i) => (i ? ctx.lineTo(s[0], s[1]) : ctx.moveTo(s[0], s[1])));
          ctx.closePath();
        });
        ctx.strokeStyle = shade(col.ice, 0.95); ctx.lineWidth = 0.8; ctx.lineJoin = 'round'; ctx.stroke();
      }

      function drawTower() {
        for (let l = 0; l < layers; l++) {
          tower.filter(p => p.layer === l)
            .map(p => ({ p, d: p.line ? p.line.reduce((a, q) => a + P(q)[2], 0) / p.line.length
                                      : p.pts.reduce((a, q) => a + P(q)[2], 0) / p.pts.length }))
            .sort((a, b) => a.d - b.d)
            .forEach(({ p }) => {
              if (p.line) {
                ctx.beginPath();
                p.line.map(P).forEach((s, i) => (i ? ctx.lineTo(s[0], s[1]) : ctx.moveTo(s[0], s[1])));
                ctx.strokeStyle = shade(col.ink, 0.45); ctx.lineWidth = 0.8; ctx.stroke();
                return;
              }
              const [b, toward] = bright(p.n);
              if (toward > 0.001) poly(p.pts, shade(col.ink, b));
            });
        }
      }

      // the tower stands beyond the cube's left face: whichever side of that
      // plane the eye is on decides what is drawn first
      const towerInFront = Ncam([-1, 0, 0])[2] > 0;
      if (towerInFront) { drawCube(); drawTower(); } else { drawTower(); drawCube(); }

      // ---- labels, in screen space ------------------------------------------
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      const fs = narrow ? GEO.scaleFontNarrow : GEO.scaleFont;
      ctx.font = '400 ' + fs + 'px ' + col.font;
      ctx.textBaseline = 'top';
      // "1 km" along the front face's bottom edge
      if (Ncam([0, -1, 0])[2] > 0.001) {
        const a = P([-H, -H, 0]), b = P([H, -H, 0]), ang = Math.atan2(b[1] - a[1], b[0] - a[0]);
        ctx.save();
        ctx.translate((a[0] + b[0]) / 2, (a[1] + b[1]) / 2); ctx.rotate(ang);
        ctx.textAlign = 'center'; ctx.fillStyle = col.dim; ctx.fillText(S.edge, 0, 4);
        ctx.restore();
      }
      // the tower's name and height, under its footprint
      const foot = [[-half, -half, 0], [half, -half, 0], [half, half, 0], [-half, half, 0]].map(q => P(at(q)));
      const fx = foot.reduce((s, q) => s + q[0], 0) / 4, fy = Math.max(...foot.map(q => q[1]));
      const lines = S.tower.map(t => fill(t, { h: fmt(T.tip, 0) }));
      const tw = Math.max(...lines.map(t => ctx.measureText(t).width));
      const lx = Math.max(tw / 2 + 1, Math.min(W - tw / 2 - 1, fx));
      ctx.textAlign = 'center';
      lines.forEach((t, i) => {
        ctx.fillStyle = i ? col.dim : col.text;
        ctx.fillText(t, lx, fy + 6 + i * (fs + 3));
      });
    }

    function resize(isNarrow) {
      narrow = isNarrow;
      const w = narrow ? GEO.scaleWNarrow : GEO.scaleW, h = narrow ? GEO.scaleHNarrow : GEO.scaleH;
      const d = Math.min(window.devicePixelRatio || 1, 2);
      if (w === W && h === Hc && d === dpr) return;
      W = w; Hc = h; dpr = d;
      cv.width = Math.round(W * dpr); cv.height = Math.round(Hc * dpr);
      cv.style.width = W + 'px'; cv.style.height = Hc + 'px';
      const lab = narrow ? GEO.scaleLabelsNarrow : GEO.scaleLabels;
      k = Math.min((W - 4) / (right - left), (Hc - 2 - lab) / (up - down));
      cx = W / 2 - k * (left + right) / 2; cy = 2 + up * k;
      draw();
    }

    new MutationObserver(() => { readColors(); draw(); })
      .observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] });
    if (document.fonts && document.fonts.ready) document.fonts.ready.then(draw);
    readColors();
    return { resize, draw };
  }

  function mount(root, opts) {
    const D = (opts && opts.data) || window.MRI_GLACIERS_DATA;
    const C = (opts && opts.content) || window.MRI_GLACIERS_CONTENT;
    const G = D.global;
    const last = G[G.length - 1];
    const cumBefore = G.find(d => d.year === C.era.from - 1).cum;    // loss up to the band's first year
    const share = Math.round(100 * (last.cum - cumBefore) / last.cum);
    const record = G.reduce((a, d) => (d.gt < a.gt ? d : a), G[0]);
    const firstGain = G.find(d => d.gt > 0);

    const M = window.MRI_GLACIERS_MAP;      // the Map tab's data (build_map.py); optional
    const state = { view: C.defaultView, surveys: false };

    // ---- skeleton -----------------------------------------------------------
    root.innerHTML = '';
    const wrap = node('div', 'mgl', null, root);
    // head: controls + legend + unit, the scale figure to their right
    const head = node('div', 'mgl-head', null, wrap);
    const controls = node('div', 'mgl-controls', null, head);
    controls.setAttribute('role', 'toolbar');
    const gView = node('div', 'mgl-group', null, controls);
    gView.setAttribute('aria-label', 'Chart view');
    const legend = node('div', 'mgl-legend', null, head);
    const unitEl = node('div', 'mgl-unit', C.legend.unit, head);
    const scaleBox = node('div', 'mgl-scale', null, head);
    const scale = C.scale ? scaleFigure(scaleBox, C.scale, wrap) : null;
    if (!scale) scaleBox.remove();
    const chart = node('div', 'mgl-chart', null, wrap);
    const s = svg('svg', { role: 'group' }, chart);
    const lanesBox = node('details', 'mgl-lanes', null, chart);   // closed by default
    node('summary', null, C.lanesSummary, lanesBox);
    node('div', 'mgl-unit', C.lanesUnit, lanesBox);
    const ls = svg('svg', { role: 'group' }, lanesBox);
    lanesBox.addEventListener('toggle', () => render());
    const tip = node('div', 'mgl-tip', null, chart);
    tip.hidden = true;
    const table = node('details', 'mgl-table', null, wrap);
    node('div', 'mgl-source', C.source, wrap);

    function chips() {
      gView.innerHTML = '';
      C.views.forEach(it => {
        const b = node('button', 'mgl-chip', it.label);
        b.type = 'button';
        b.setAttribute('aria-pressed', String(state.view === it.id));
        b.addEventListener('click', () => { state.view = it.id; render(); });
        gView.appendChild(b);
      });
    }

    // ---- tooltip ------------------------------------------------------------
    function place(px, py) {
      tip.hidden = false;
      const w = tip.offsetWidth, h = tip.offsetHeight;
      let x = px + 14, y = py + 14;
      if (x + w > chart.clientWidth) x = Math.max(0, px - w - 14);
      if (y + h > chart.clientHeight) y = Math.max(0, py - h - 14);
      tip.style.left = x + 'px';
      tip.style.top = y + 'px';
    }
    function row(parent, cls, strong, rest) {
      const r = node('div', 'row', null, parent);
      node('span', 'key ' + cls, null, r);
      const t = node('span', null, null, r);
      if (strong != null) node('b', null, strong, t);
      t.appendChild(document.createTextNode(rest));
      return r;
    }
    function yearTip(d) {
      tip.innerHTML = '';
      node('div', 'h', String(d.year), tip);
      node('div', 'sub', C.tooltip.year, tip);
      row(tip, d.gt > 0 ? 'gain' : 'loss', signed(d.gt, 0) + ' ± ' + fmt(d.sigma, 0) + ' Gt', ' ' + C.tooltip.annual);
      row(tip, 'plain', signed(d.mwe, 2) + ' m w.e.', ' ' + C.tooltip.thinning);
      row(tip, 'band', signed(d.cum, 0) + ' Gt', ' ' + C.tooltip.cum);
      if (d.sleCum > 0) row(tip, 'plain', '+' + fmt(d.sleCum, 1) + ' mm', ' ' + C.tooltip.sle);
    }
    function regionTip(r) {
      tip.innerHTML = '';
      node('div', 'h', C.regionNames[r.code] || r.code, tip);
      row(tip, r.gt > 0 ? 'gain' : 'loss', signed(r.gt, 0) + ' Gt', ' ' + C.tooltip.regionGt);
      row(tip, 'plain', signed(r.mwe, 1) + ' m w.e.', ' ' + C.tooltip.regionMwe);
      row(tip, 'plain', fmt(r.area, 0) + ' km²', ' ' + C.tooltip.area);
      if (C.notes && C.notes[r.code]) node('div', 'note', C.notes[r.code], tip);
    }
    function cellTip(c) {
      tip.innerHTML = '';
      node('div', 'h', fill(C.map.tipHead, { n: fmt(c[2], 0) }), tip);
      row(tip, 'plain', fmt(c[3], c[3] < 10 ? 1 : 0) + ' km²', ' ' + C.map.tipArea);
      row(tip, 'th' + thClass(c[4]), fmt(c[4], 0) + ' m', ' ' + C.map.tipThick);
    }
    const thClass = t => C.map.classes.findIndex(k => t < k.below) === -1
      ? C.map.classes.length - 1 : C.map.classes.findIndex(k => t < k.below);
    function hide() {
      tip.hidden = true;
      wrap.classList.remove('is-hover-year', 'is-hover-lane');
      wrap.querySelectorAll('.on').forEach(n => n.classList.remove('on'));
    }
    // two hover scopes: a year dims the other columns, a lane the other lanes
    function highlight(sel, cls) {
      wrap.classList.add(cls);
      wrap.querySelectorAll('.on').forEach(n => n.classList.remove('on'));
      if (sel) wrap.querySelectorAll(sel).forEach(n => n.classList.add('on'));
    }
    function local(evt) {
      const r = chart.getBoundingClientRect();
      return [evt.clientX - r.left, evt.clientY - r.top];
    }
    function anchor(elm) {
      const r = elm.getBoundingClientRect(), c = chart.getBoundingClientRect();
      return [r.left - c.left + r.width / 2, r.top - c.top + r.height / 2];
    }
    document.addEventListener('pointerdown', e => { if (!chart.contains(e.target)) hide(); });

    // ---- the Map tab: where the glaciers are, and how thick ----------------
    // Figure 3's Robinson basemap; one dot per cell of glaciers, its area as
    // the dot's area, its mean thickness as one of a few colour classes.
    function drawMap(W, narrow) {
      const F = M.frame, k = W / F.w;
      const pad = (narrow ? GEO.padT : GEO.padT + GEO.gainsRoom) / k;   // same room above as the charts
      s.innerHTML = '';
      s.setAttribute('viewBox', `0 ${-pad} ${F.w} ${F.h + pad}`);
      s.setAttribute('height', Math.round((F.h + pad) * k));
      s.setAttribute('aria-label', fill(C.map.aria, { n: fmt(M.totals.glaciers, 0) }));
      const toPath = r => { let d = 'M' + r[0] + ',' + r[1]; for (let i = 2; i < r.length; i += 2) d += 'L' + r[i] + ',' + r[i + 1]; return d + 'Z'; };
      svg('path', { class: 'map-sphere', d: toPath(M.sphere[0]) }, s);
      svg('path', { class: 'map-land', d: M.land.map(toPath).join('') }, s);
      const maxA = M.cells[0][3];
      const rMax = (narrow ? GEO.mapRMaxNarrow : GEO.mapRMax) / k, rMin = GEO.mapRMin / k;
      const g = svg('g', { class: 'map-cells' }, s);
      M.cells.forEach(c => {                        // biggest first, so small cells stay on top
        const dot = svg('circle', { class: 'cell th' + thClass(c[4]), cx: c[0], cy: c[1],
          r: rMin + (rMax - rMin) * Math.sqrt(c[3] / maxA) }, g);
        dot.addEventListener('pointerenter', evt => { cellTip(c); dot.classList.add('on'); place(...local(evt)); });
        dot.addEventListener('pointermove', evt => place(...local(evt)));
        dot.addEventListener('pointerleave', () => { dot.classList.remove('on'); hide(); });
      });
      if (state.surveys) {
        const gs = svg('g', { class: 'map-surveys' }, s);
        M.surveys.forEach(p => svg('circle', { cx: p[0], cy: p[1], r: GEO.surveyR / k }, gs));
      }
    }

    // ---- draw ---------------------------------------------------------------
    function render() {
      const W = chart.clientWidth;
      if (!W) return;
      const narrow = W < GEO.narrowAt;
      const cum = state.view === 'cum';
      wrap.classList.toggle('is-narrow', narrow);
      if (scale) scale.resize(narrow);
      chips();

      // legend and unit line, per view
      const isMap = state.view === 'map' && M;
      legend.innerHTML = '';
      if (isMap) {
        node('span', 'mgl-key-title', C.map.legendTitle, legend);
        C.map.classes.forEach((k, i) => {
          const el = node('span', 'mgl-key', null, legend);
          node('span', 'mgl-swatch dot th' + i, null, el);
          el.appendChild(document.createTextNode(k.label));
        });
        const t = node('button', 'mgl-chip mgl-layer', null, legend);     // GlaThiDa on/off
        t.type = 'button';
        t.setAttribute('aria-pressed', String(state.surveys));
        node('span', 'mgl-swatch survey', null, t);
        t.appendChild(document.createTextNode(C.map.surveys));
        t.addEventListener('click', () => { state.surveys = !state.surveys; render(); });
        unitEl.textContent = fill(C.map.unit, { deg: M.cellDeg, n: fmt(M.totals.glaciers, 0),
          area: fmt(M.totals.areaKm2, 0) });
      } else {
        [['loss', C.legend.loss], ['gain', C.legend.gain], [cum ? 'band' : 'whisk', C.legend.band]]
          .forEach(([c, label]) => {
            const k = node('span', 'mgl-key', null, legend);
            node('span', 'mgl-swatch ' + c, null, k);
            k.appendChild(document.createTextNode(label));
          });
        unitEl.textContent = C.legend.unit;
      }

      // scales: years as columns, one shared x for the chart and the lanes
      const plotH = narrow ? GEO.plotHNarrow : GEO.plotH;
      const from = D.from, to = D.to;
      const L = narrow ? 48 : GEO.padL, R = W - GEO.padR, cw = (R - L) / (to - from + 1);
      const x = yr => L + (yr - from + 0.5) * cw;
      const bw = cw >= 4 ? Math.min(cw - GEO.gap, GEO.brickMaxW) : Math.max(cw - 0.6, 1);
      const rx = Math.min(1.5, bw / 3);

      if (isMap) drawMap(W, narrow);
      else {
      // y domain per view, padded to round values
      let top, bot, step;
      if (cum) {
        top = Math.ceil(Math.max(0, ...G.map(d => d.cum + d.cumSigma)) / 50) * 50;
        bot = Math.floor(Math.min(...G.map(d => d.cum - d.cumSigma)) / 500) * 500;
        step = 2000;                                  // adjust gridline spacing here
      } else {
        top = Math.ceil(Math.max(0, ...G.map(d => d.gt + d.sigma)) / 50) * 50;
        bot = Math.floor(Math.min(...G.map(d => d.gt - d.sigma)) / 50) * 50;
        step = 200;
      }
      // extra room above the plot, where the foot of the scale figure tucks in on
      // the right. Same in both views, so
      // switching views does not change the chart's height
      const padT = GEO.padT + (narrow ? 0 : GEO.gainsRoom);
      const y = v => padT + (top - v) / (top - bot) * plotH;
      const plotBot = padT + plotH;
      const H = plotBot + GEO.axisH;

      s.innerHTML = '';
      s.setAttribute('viewBox', `0 0 ${W} ${H}`);
      s.setAttribute('height', H);
      s.setAttribute('aria-label',
        `Glacier mass change ${from}–${to}: ${fmt(last.cum, 0)} gigatonnes in total, ` +
        `${fmt(last.sleCum, 0)} mm of sea-level rise. Details in the table below.`);

      // era band: the years since 2000, behind everything
      const eraX = x(C.era.from) - cw / 2;
      svg('rect', { class: 'era', x: eraX, y: padT, width: R - eraX, height: plotH }, s);
      svg('line', { class: 'era-edge', x1: eraX, x2: eraX, y1: padT, y2: plotBot }, s);

      // gridlines + y labels; the topmost label carries the unit. Zero gets a
      // label but no gridline: the baseline is drawn there
      const grid = svg('g', { class: 'grid tick' }, s);
      const gridVals = [];
      for (let v = Math.ceil(bot / step) * step; v <= top; v += step) gridVals.push(v);
      gridVals.reverse().forEach((v, i) => {
        if (v) svg('line', { x1: L, x2: R, y1: y(v), y2: y(v) }, grid);
        const t = svg('text', { x: L - 8, y: y(v) + 4, 'text-anchor': 'end' }, grid);
        t.textContent = fmt(v, 0) + (i === 0 && !narrow ? ' Gt' : '');
      });

      // uncertainty band around the staircase (cumulative view only)
      if (cum) {
        let up = '', down = '';
        G.forEach(d => {
          const x0 = x(d.year) - cw / 2, x1 = x(d.year) + cw / 2;
          up += `L${x0},${y(d.cum + d.cumSigma)} L${x1},${y(d.cum + d.cumSigma)} `;
          // the lower edge is walked back right to left, so each year's corners go right then left
          down = `L${x1},${y(d.cum - d.cumSigma)} L${x0},${y(d.cum - d.cumSigma)} ` + down;
        });
        svg('path', { class: 'band', d: ('M' + up.slice(1) + down + 'Z').replace(/L([^ ]+) Z$/, 'L$1Z') }, s);
      }

      // the staircase's leading edge, so the silhouette holds where the
      // yearly steps are only a pixel or two tall (cumulative view only)
      if (cum) {
        let d = `M${x(from) - cw / 2},${y(G[0].cum)}`;
        G.forEach((g, i) => {
          d += `H${x(g.year) + cw / 2}`;
          if (i < G.length - 1) d += `V${y(G[i + 1].cum)}`;
        });
        svg('path', { class: 'edge', d }, s);
      }

      // one block per year
      const gCols = svg('g', {}, s), gHits = svg('g', {}, s);
      G.forEach((d, i) => {
        const prev = cum ? (i ? G[i - 1].cum : 0) : 0;
        const v0 = cum ? prev : 0, v1 = cum ? d.cum : d.gt;
        const gain = v1 > v0;
        const yTop = Math.min(y(v0), y(v1));
        const h = Math.max(Math.abs(y(v1) - y(v0)), 1.25);
        svg('rect', { class: 'brick ' + (gain ? 'gain' : 'loss'), 'data-year': d.year,
          x: x(d.year) - bw / 2, y: gain ? y(v0) - h : yTop, width: bw, height: h, rx }, gCols);
        if (!cum) svg('line', { class: 'whisk', 'data-year': d.year,
          x1: x(d.year), x2: x(d.year), y1: y(d.gt - d.sigma), y2: y(d.gt + d.sigma) }, gCols);
        // hover areas start just above the plot, so the room above it stays inert
        const hit = svg('rect', { class: 'col-hit', x: x(d.year) - cw / 2, y: padT - 6, width: cw,
          height: plotBot - padT + 12 }, gHits);
        const show = evt => { yearTip(d); highlight(`[data-year="${d.year}"]`, 'is-hover-year'); place(...local(evt)); };
        hit.addEventListener('pointerenter', show);
        hit.addEventListener('pointermove', evt => place(...local(evt)));
        hit.addEventListener('pointerleave', hide);
      });
      svg('line', { class: 'baseline', x1: L, x2: R, y1: y(0), y2: y(0) }, s);

      // the band's share of the loss, at the same height in both views: under the
      // zero line of the cumulative view, above the bars of the yearly one
      const eraY = padT + (narrow ? 24 : 30);                          // adjust band label position here
      (narrow && C.era.noteNarrow ? C.era.noteNarrow : [C.era.note]).forEach((t, i) => {
        svg('text', { class: 'era-label', x: eraX + 8, y: eraY + i * 14 }, s).textContent = fill(t, { share });
      });

      // ---- annotations ------------------------------------------------------
      if (cum) {
        // the big number, in the empty lower left of the descending staircase
        const kx = L + (R - L) * 0.05, ky = plotBot - plotH * 0.31;   // adjust key number position here (0.31 sits it between two gridlines)
        const key = svg('text', { class: 'key-gt', x: kx, y: ky,
          'font-size': narrow ? GEO.keySizeNarrow : GEO.keySize }, s);
        key.textContent = fill(C.annotations.keyGt, { gt: fmt(last.cum, 0) });
        if (!narrow) {              // on phones the deck above the figure carries these lines instead
          svg('text', { class: 'key-sub', x: kx + 2, y: ky + 20 }, s).textContent = C.annotations.keySub1;
        }
      } else if (!narrow) {
        // the record year, labelled beside its bar with a little clearance
        const lab = svg('text', { class: 'ann', x: x(record.year) - bw / 2 - 8, y: y(record.gt) + 4,
          'text-anchor': 'end' }, s);
        lab.textContent = fill(C.annotations.record, { gt: fmt(record.gt, 0) });
      }
      // the handful of gain years, hollow bars: noted above the early bars of the
      // yearly view, its leader dropping to the last of them (1992)
      if (!cum && !narrow) {
        const lastGain = G.filter(d => d.gt > 0).pop();
        const lx = x(lastGain.year);
        const labY = GEO.padT + 14;                                    // in the room above the plot (adjust here)
        C.annotations.gains.forEach((line, k) =>
          svg('text', { class: 'ann', x: lx + 8, y: labY + k * 15, 'text-anchor': 'end' }, s).textContent = line);
        // leader from under the note down to just above 1992's whisker
        svg('line', { class: 'ann-leader', x1: lx, x2: lx, y1: labY + 15 + 6,
          y2: y(lastGain.gt + lastGain.sigma) - 3 }, s);
      }

      // year axis
      const steps = [1, 2, 5, 10, 20, 25, 50];
      const tstep = steps.find(st => st * cw >= GEO.tickMinPx) || 50;
      const ax = svg('g', { class: 'tick' }, s);
      for (let yr = Math.ceil(from / tstep) * tstep; yr <= to; yr += tstep) {
        svg('line', { class: 'baseline', x1: x(yr), x2: x(yr), y1: plotBot, y2: plotBot + 4 }, ax);
        const t = svg('text', { x: x(yr), y: plotBot + 17, 'text-anchor': 'middle' }, ax);
        t.textContent = yr;
      }

      }   // end of the chart views

      // ---- region lanes: cumulative thinning, one shared m w.e. scale -------
      ls.innerHTML = '';
      if (lanesBox.open) {
        const all = D.regions.flatMap(r => r.cumMwe);
        const sTop = Math.max(0, ...all) + 1, sBot = Math.min(...all) - 1;
        const sy = v => (sTop - v) / (sTop - sBot) * GEO.laneSpark;
        let topY = 6;
        D.regions.forEach(r => {
          const g = svg('g', { class: 'lane' }, ls);
          const name = svg('text', { class: 'lane-label', x: L, y: topY + 11 }, g);
          name.textContent = C.regionNames[r.code] || r.code;
          const val = svg('text', { class: 'lane-value', x: R, y: topY + 11, 'text-anchor': 'end' }, g);
          const flag = C.regionFlags && C.regionFlags[r.code];
          val.textContent = signed(r.gt, 0) + ' Gt · ' + signed(r.mwe, 1) + ' m w.e.' +
            (flag ? ' · ' + flag : '');
          const y0 = topY + GEO.laneHead;
          svg('line', { class: 'lane-base', x1: L, x2: R, y1: y0 + sy(0), y2: y0 + sy(0) }, g);
          let pts = '', area = `M${x(from)},${y0 + sy(0)} `;
          G.forEach((d, i) => {
            const p = `${x(d.year)},${y0 + sy(r.cumMwe[i])}`;
            pts += p + ' '; area += 'L' + p + ' ';
          });
          area += `L${x(to)},${y0 + sy(0)}Z`;
          svg('path', { class: 'spark-area', d: area }, g);
          svg('polyline', { class: 'spark-line', points: pts.trim() }, g);
          const hit = svg('rect', { class: 'lane-hit', x: L, y: topY, width: R - L,
            height: GEO.laneHead + GEO.laneSpark, tabindex: 0,
            'aria-label': `${C.regionNames[r.code] || r.code}: ${signed(r.gt, 0)} gigatonnes` }, g);
          const show = pt => { regionTip(r); highlight(null, 'is-hover-lane'); g.classList.add('on'); place(...pt); };
          hit.addEventListener('pointerenter', evt => show(local(evt)));
          hit.addEventListener('pointermove', evt => place(...local(evt)));
          hit.addEventListener('pointerleave', hide);
          hit.addEventListener('focus', () => show(anchor(hit)));
          hit.addEventListener('blur', hide);
          topY += GEO.laneHead + GEO.laneSpark + GEO.laneGap;
        });
        ls.setAttribute('viewBox', `0 0 ${W} ${topY}`);
        ls.setAttribute('height', topY);
      }

      // table view (regions, most loss first, with the world total on top)
      const open = table.open;
      table.innerHTML = '';
      table.open = open;
      node('summary', null, C.tableSummary, table);
      const tb = node('table', null, null, table);
      const hr = node('tr', null, null, node('thead', null, null, tb));
      C.tableHead.forEach((h, k) => node('th', k ? 'num' : null, h, hr));
      const body = node('tbody', null, null, tb);
      const totMwe = G.reduce((a, d) => a + d.mwe, 0);
      // the world total carries its 1-sigma; a flagged region gets the * note
      [[C.tableWorld, signed(last.cum, 0) + ' ± ' + fmt(last.cumSigma, 0), totMwe, last.area]]
        .concat(D.regions.map(r => [C.regionNames[r.code] || r.code,
          signed(r.gt, 0) + (C.regionFlags && C.regionFlags[r.code] ? '*' : ''), r.mwe, r.area]))
        .forEach(([nm, gtText, mwe, area], i) => {
          const r = node('tr', i ? null : 'world', null, body);
          node('td', null, nm, r);
          node('td', 'num', gtText, r);
          node('td', 'num', signed(mwe, 1), r);
          node('td', 'num', fmt(area, 0), r);
        });
      if (C.tableFlag && C.regionFlags && Object.keys(C.regionFlags).length)
        node('div', 'mgl-table-note', C.tableFlag, table);
    }

    // Redraw on width changes only, and in the next frame (see Figure 1's
    // timeline.js for why: a redraw changes the height and would otherwise
    // trip the browser's "ResizeObserver loop" error).
    let lastW = chart.clientWidth, queued = 0;
    new ResizeObserver(() => {
      if (queued) return;
      queued = requestAnimationFrame(() => {
        queued = 0;
        if (chart.clientWidth !== lastW) { lastW = chart.clientWidth; render(); }
      });
    }).observe(chart);
    render();
    return { render };
  }

  window.MRIGlaciers = { mount };
})();
