/* ---------------------------------------------------------------------------
   Populations & hazards - draws window.MRI_HAZARDS_DATA (hand-transcribed
   from CCP5) and window.MRI_HAZARDS_GEO (generated by build_assets.py) with
   the wording in window.MRI_HAZARDS_CONTENT (hazards-content.js).

   An Equal Earth map on Figure 2's basemap (same sources, simplification
   and sphere/land/mountain treatment) with one dot per assessed IPCC
   reference region, coloured by risk at the warming level chosen in the
   chips (landslides & floods at three GWLs, or water at 1.5-2C). Underneath,
   one card per IPCC continental region counts who lives in the mountains in
   2015; a collapsible table lists every assessed region.

   Vanilla JS + SVG, no dependencies. Usage:
       MRIHazards.mount(document.getElementById('fig'));
   The component sizes itself to its container and redraws on resize.
--------------------------------------------------------------------------- */
(function () {
  'use strict';

  const SVGNS = 'http://www.w3.org/2000/svg';

  // adjust figure geometry here (px)
  const GEO = {
    dotR: 6.5,           // risk-dot radius on screen
    dotRNarrow: 5,       // ... below narrowAt
    narrowAt: 560
  };

  function svg(tag, attrs, parent) {
    const n = document.createElementNS(SVGNS, tag);
    for (const k in attrs) n.setAttribute(k, attrs[k]);
    if (parent) parent.appendChild(n);
    return n;
  }
  function node(tag, cls, text, parent) {
    const n = document.createElement(tag);
    if (cls) n.className = cls;
    if (text != null) n.textContent = text;   // untrusted strings only ever go in as text
    if (parent) parent.appendChild(n);
    return n;
  }
  function millions(n, digits) {
    const m = n / 1e6;
    if (digits == null || m < 1) digits = m >= 10 ? 0 : 1;   // below 1 M, a decimal always
    return m.toLocaleString('en-GB', { minimumFractionDigits: digits, maximumFractionDigits: digits });
  }

  function mount(root, opts) {
    const D = (opts && opts.data) || window.MRI_HAZARDS_DATA;
    const C = (opts && opts.content) || window.MRI_HAZARDS_CONTENT;
    const G = (opts && opts.geo) || window.MRI_HAZARDS_GEO;

    const state = { view: 'gwl0', cont: null };   // view: gwl0|gwl1|gwl2|water; cont: continent filter or null

    // ---- skeleton ---------------------------------------------------------
    root.innerHTML = '';
    const wrap = node('div', 'mhz', null, root);

    const controls = node('div', 'mhz-controls', null, wrap);
    controls.setAttribute('role', 'toolbar');
    node('span', 'mhz-grouplabel', C.gwlGroupLabel, controls);
    const gGwl = node('div', 'mhz-group', null, controls);
    const chips = [];
    C.gwl.forEach((g, i) => {
      const b = node('button', 'mhz-chip', g.label, gGwl);
      b.type = 'button';
      if (g.note) b.title = g.note;
      b.addEventListener('click', () => { state.view = 'gwl' + i; update(); });
      chips.push(b);
    });
    node('div', 'mhz-sep', null, controls);
    const bWater = node('button', 'mhz-chip', C.waterChip, controls);
    bWater.type = 'button';
    bWater.addEventListener('click', () => { state.view = 'water'; update(); });
    chips.push(bWater);

    const legend = node('div', 'mhz-legend', null, wrap);
    const legKeys = {};
    /* "Low" leads the ramp; it only exists in the water assessment, so it is
       shown in that view alone (see update()) */
    const low = node('span', 'mhz-key', null, legend);
    node('span', 'mhz-swatch low', null, low);
    node('span', null, 'Low', low);
    legKeys.low = low;
    C.legend.levels.forEach(([lv, label]) => {
      const k = node('span', 'mhz-key', null, legend);
      node('span', 'mhz-swatch ' + lv, null, k);
      node('span', null, label, k);
      legKeys[lv] = k;
    });

    // ---- map --------------------------------------------------------------
    const mapBox = node('div', 'mhz-map', null, wrap);
    const W = G.frame.w, H = G.frame.h;
    const chart = svg('svg', { viewBox: '0 0 ' + W + ' ' + H }, mapBox);
    chart.setAttribute('role', 'img');
    const toPath = flat => {
      let d = '';
      for (let i = 0; i < flat.length; i += 2) d += (i ? 'L' : 'M') + flat[i] + ' ' + flat[i + 1];
      return d + 'Z';
    };
    /* sphere + land + mountain areas, drawn exactly as in Figure 2 */
    svg('path', { class: 'sphere', d: toPath(G.sphere[0]) }, chart);
    svg('path', { class: 'land', d: G.land.map(toPath).join('') }, chart);
    const gmba = svg('path', { class: 'gmba', d: G.gmba.map(toPath).join('') }, chart);
    gmba.style.display = 'none';
    const gDots = svg('g', {}, chart);

    /* the mountain-layer toggle lives on the map, styled apart from the chips (as in Figure 2);
       the layer starts hidden */
    const layerBtn = node('button', 'mhz-layer', null, mapBox);
    layerBtn.type = 'button';
    node('span', 'sw', null, layerBtn);
    layerBtn.appendChild(document.createTextNode(C.legend.mountains));
    layerBtn.setAttribute('aria-pressed', 'false');
    layerBtn.addEventListener('click', () => {
      const on = layerBtn.getAttribute('aria-pressed') !== 'true';
      layerBtn.setAttribute('aria-pressed', String(on));
      gmba.style.display = on ? '' : 'none';
    });

    // ---- cards ------------------------------------------------------------
    const cardsBox = node('div', 'mhz-cards', null, wrap);

    // ---- footer + matrix --------------------------------------------------
    const matrix = node('details', 'mhz-matrix', null, wrap);
    node('summary', null, C.matrixSummary, matrix);
    /* graphical confidence key, only visible while the panel is open: one
       schematic cell per step, with the same pips the table cells use */
    const mKey = node('div', 'mhz-matrixkey', null, matrix);
    node('span', null, C.matrixKey, mKey);
    C.legend.confWord.forEach((word, i) => {
      const item = node('span', 'k', null, mKey);
      const cell = node('span', 'mhz-cell key', null, item);
      for (let j = 0; j <= i; j++) node('i', null, null, cell);
      node('span', null, word[0].toUpperCase() + word.slice(1), item);
    });
    const sourceLine = node('p', 'mhz-source', C.footer.source, wrap);

    const tip = node('div', 'mhz-tip', null, wrap);
    tip.hidden = true;

    // ---- tooltip plumbing -------------------------------------------------
    function showTip(evt, build) {
      tip.innerHTML = '';
      build(tip);
      tip.hidden = false;
      const wr = wrap.getBoundingClientRect();
      const w = tip.offsetWidth, h = tip.offsetHeight;
      let x = evt.clientX - wr.left + 14, y = evt.clientY - wr.top + 12;
      if (x + w > wr.width - 4) x = Math.max(4, evt.clientX - wr.left - w - 14);
      if (y + h > wr.height - 4) y = Math.max(4, evt.clientY - wr.top - h - 12);
      tip.style.left = x + 'px';
      tip.style.top = y + 'px';
    }
    function hideTip() { tip.hidden = true; }

    const confWord = c => C.legend.confWord[Math.max(0, Math.min(3, c - 1))] + ' ' + C.legend.confidence;
    function riskRow(parent, level, conf, label) {
      const r = node('div', 'row', null, parent);
      node('span', 'key ' + (level || 'na'), null, r);
      const t = node('span', null, null, r);
      const name = level ? (C.legend.levels.find(l => l[0] === level) ||
                            [null, level === 'low' ? 'Low' : level])[1] : C.legend.levels[3][1];
      t.textContent = label + ': ';
      const b = node('b', null, name, t);
      if (level && conf) node('span', 'dimtext', ' · ' + confWord(conf), t);
      return r;
    }

    // ---- subregion dots ---------------------------------------------------
    const bySub = {};
    function drawDots() {
      gDots.innerHTML = '';
      const scale = W / Math.max(1, mapBox.clientWidth || W);
      const r = (wrap.classList.contains('is-narrow') ? GEO.dotRNarrow : GEO.dotR) * scale;
      D.subregions.forEach(s => {
        const a = G.subAnchors[s.id];
        if (!a) return;
        const lv = levelOf(s);
        const c = svg('circle', {
          class: 'mhz-dot ' + (lv || 'na'),
          cx: a[0], cy: a[1], r: lv ? r : r * 0.72,
          tabindex: '0', role: 'img'
        }, gDots);
        c.setAttribute('aria-label', s.name + ', ' + levelWord(lv));
        /* a larger invisible ring makes the dot reachable with a finger */
        const hit = svg('circle', { cx: a[0], cy: a[1], r: r + 8 * (W / Math.max(1, mapBox.clientWidth || W)),
                                    fill: 'transparent' }, gDots);
        [c, hit].forEach(el => {
          el.addEventListener('mousemove', e => { mapBox.classList.add('is-hover'); c.classList.add('on'); showTip(e, t => subTip(t, s)); });
          el.addEventListener('mouseleave', () => { mapBox.classList.remove('is-hover'); c.classList.remove('on'); hideTip(); });
        });
        c.addEventListener('focus', () => {
          const b = c.getBoundingClientRect();
          showTip({ clientX: b.left + b.width / 2, clientY: b.top + b.height }, t => subTip(t, s));
        });
        c.addEventListener('blur', hideTip);
        bySub[s.id] = { dot: c, hit: hit };
      });
    }
    function levelWord(lv) {
      if (!lv) return C.legend.levels[3][1];
      const f = C.legend.levels.find(l => l[0] === lv);
      return f ? f[1] : 'Low';
    }
    function levelOf(s) {
      if (state.view === 'water') return s.water ? s.water[0] : null;
      const i = +state.view.slice(3);
      return s.haz && s.haz[i] ? s.haz[i][0] : null;
    }
    function subTip(t, s) {
      node('div', 'h', s.name, t);
      node('div', 'sub', s.id + ' · ' + C.tooltip.subregions.replace('this region',
        (D.continents.find(c => c.id === s.cont) || {}).name || s.cont), t);
      C.gwl.forEach((g, i) => {
        const hz = s.haz && s.haz[i];
        riskRow(t, hz ? hz[0] : null, hz ? hz[1] : 0, g.label);
      });
      riskRow(t, s.water ? s.water[0] : null, s.water ? s.water[1] : 0, C.tooltip.water);
      const noteText = C.notes[s.id];
      if (noteText) {
        const u = node('div', 'upd', null, t);
        node('b', null, C.tooltip.updated + ': ', u);
        u.appendChild(document.createTextNode(noteText));
      }
    }

    // ---- continental cards ------------------------------------------------
    const byCard = {};
    function setCont(id) {
      state.cont = state.cont === id ? null : id;
      update();
    }
    function drawCards() {
      cardsBox.innerHTML = '';
      D.continents.forEach(cn => {
        const p = G.pop[cn.name];
        if (!p) return;
        /* no card for a region with nothing assessed at either scale
           (Small Islands): its population still counts toward the total */
        if (!cn.risk && !D.subregions.some(s => s.cont === cn.id)) return;
        const card = node('div', 'mhz-card', null, cardsBox);
        /* a card filters the map to its continent; Small Islands has no
           assessed subregions, so nothing to filter */
        const hasDots = D.subregions.some(s => s.cont === cn.id);
        if (hasDots) {
          card.tabIndex = 0;
          card.setAttribute('role', 'button');
          card.setAttribute('aria-pressed', 'false');
          byCard[cn.id] = card;
          card.addEventListener('click', () => setCont(cn.id));
          card.addEventListener('keydown', e => {
            if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); setCont(cn.id); }
          });
        } else {
          card.classList.add('nofilter');
        }
        node('div', 'nm', cn.name, card);
        const big = node('div', 'big', null, card);
        big.appendChild(document.createTextNode(millions(p.pop2015)));
        node('small', null, ' M people', big);
        node('div', 'hzline', cn.hazards
          ? C.cards.hazardRow + ': ' + cn.hazards.map(h => C.hazardNames[h]).join(' · ')
          : C.cards.notAssessed, card);
      });
    }

    // ---- subregion matrix -------------------------------------------------
    function drawMatrix() {
      const old = matrix.querySelector('table');
      if (old) old.remove();
      const tb = document.createElement('table');
      matrix.appendChild(tb);
      const hr = tb.insertRow();
      const th = (txt, cls) => {
        const h = document.createElement('th');
        h.textContent = txt;
        if (cls) h.className = cls;
        hr.appendChild(h);
      };
      th(C.matrixCols.region);
      C.gwl.forEach(g => th(g.label, 'c'));
      th(C.matrixCols.water, 'c');
      D.subregions.forEach(s => {
        const row = tb.insertRow();
        const rg = row.insertCell();
        rg.className = 'rg';
        rg.appendChild(document.createTextNode(s.name + ' '));
        const sm = document.createElement('small');
        sm.textContent = s.id;
        rg.appendChild(sm);
        const cell = pair => {
          const td = row.insertCell();
          td.className = 'c';
          const el = node('span', 'mhz-cell ' + (pair ? pair[0] : 'na'), null, td);
          if (pair) for (let i = 0; i < pair[1]; i++) node('i', null, null, el);
          td.title = pair ? ((C.legend.levels.find(l => l[0] === pair[0]) ||
            [null, 'Low'])[1] + ' · ' + confWord(pair[1])) : C.legend.levels[3][1];
        };
        C.gwl.forEach((g, i) => cell(s.haz ? s.haz[i] : null));
        cell(s.water);
      });
    }

    // ---- view switching ---------------------------------------------------
    function update() {
      chips.forEach((b, i) => {
        const on = state.view === (i < 3 ? 'gwl' + i : 'water');
        b.setAttribute('aria-pressed', on ? 'true' : 'false');
      });
      legKeys.low.style.display = state.view === 'water' ? '' : 'none';
      D.subregions.forEach(s => {
        const e = bySub[s.id];
        if (!e) return;
        const lv = levelOf(s);
        const off = state.cont && s.cont !== state.cont;
        e.dot.setAttribute('class', 'mhz-dot ' + (lv || 'na') + (off ? ' off' : ''));
        e.dot.setAttribute('aria-label', s.name + ', ' + levelWord(lv));
        e.dot.setAttribute('tabindex', off ? '-1' : '0');
        e.hit.style.pointerEvents = off ? 'none' : '';
      });
      for (const id in byCard) byCard[id].setAttribute('aria-pressed', String(state.cont === id));
    }

    // ---- first draw + resize ----------------------------------------------
    let raf = 0, lastW = 0;
    function layout() {
      const w = wrap.clientWidth;
      if (w === lastW || !w) return;
      lastW = w;
      wrap.classList.toggle('is-narrow', w < GEO.narrowAt);
      drawDots();
      update();
    }
    drawCards();
    drawMatrix();
    layout();
    if (!lastW) {                      // mounted while hidden: draw once anyway
      drawDots();
      update();
    }
    new ResizeObserver(() => {         // redraws deferred to rAF (bundler shows every window error)
      cancelAnimationFrame(raf);
      raf = requestAnimationFrame(layout);
    }).observe(wrap);
  }

  window.MRIHazards = { mount };
})();
