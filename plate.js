      var all = window.STORIES || (window.MRI_CONTENT && window.MRI_CONTENT.STORIES);
      if (!all) return false;
      for (var i = 0; i < all.length; i++) {
        if (all[i].num === num) return all[i].status && all[i].status !== 'draft';
      }
