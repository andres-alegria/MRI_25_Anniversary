#!/usr/bin/env python3
"""Write plate.js from the generated artwork.

The page needs three things the moment it constructs: the order of the climb,
each story's position on the plate, and a host to inject the drawing into.
The drawing itself is a file (art/range-<theme>.svg) and arrives over the
network, so only the small station table is baked into plate.js here.

    python3 tools/make-plate-js.py

Re-run it after regenerating the art (tools/range3d/render.py).
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
st = json.loads((ROOT / 'art' / 'stations.json').read_text())
W, H = st['width'], st['height']

rows = []
for s in sorted(st['stations'], key=lambda q: q['order']):
    rows.append('  { order: %d, story: %d, px: %.2f, py: %.2f }' % (
        s['order'], s['story'], s['x'] / W * 100, s['y'] / H * 100))
table = ',\n'.join(rows)

js = '''/* ---------------------------------------------------------------------------
   MRI 25th Anniversary — the mountain plate

   The artwork is a generated block diagram of the range (tools/range3d), kept
   as a file rather than drawn in the browser: art/range-dark.svg and
   art/range-light.svg, %(W)d x %(H)d. This file fetches the one that matches the
   theme, injects it into the page's <svg> host, and tells the page where each
   story's marker belongs.

   Consumed elsewhere:
     window.MRI_PLATE.nodes    {storyNumber: {px, py}} in per-cent of the plate
     window.MRI_PLATE.byClimb  {climbNumber: {px, py}} — what the markers use
     window.MRI_PLATE.stories  the climb order, so the index can follow it

   Generated by tools/make-plate-js.py — edit that, not this.
--------------------------------------------------------------------------- */
(function () {
  'use strict';

  var VIEWBOX = '0 0 %(W)d %(H)d';
  var AW = %(W)d, AH = %(H)d;          /* the drawing's own size, in its units */
  var ART = { dark: 'art/range-dark.svg', light: 'art/range-light.svg' };

  /* station order on the climb, and where each one sits on the plate */
  var STATIONS = [
%(table)s
  ];

  var nodes = {}, byClimb = {}, stories = [];
  STATIONS.forEach(function (s) {
    var node = { px: s.px, py: s.py, num: s.story, climb: s.order };
    nodes[s.story] = node;
    byClimb[s.order] = node;
    stories.push({ num: s.story, climb: s.order });
  });

  function theme() {
    return document.documentElement.getAttribute('data-theme') === 'light' ? 'light' : 'dark';
  }

  window.MRI_PLATE = {
    svg: '', viewBox: VIEWBOX, nodes: nodes, byClimb: byClimb, stories: stories,
    layout: { frame: %(W)d / %(H)d, marker: 26 }, theme: theme(), focus: null
  };

  /* --- the drawing --------------------------------------------------------
     Fetched once per theme and cached, so switching back and forth does not
     go back to the network. */
  var cache = {};
  function load(which) {
    if (cache[which]) return Promise.resolve(cache[which]);
    return fetch(ART[which]).then(function (r) {
      if (!r.ok) throw new Error('plate ' + which + ': ' + r.status);
      return r.text();
    }).then(function (txt) { cache[which] = txt; return txt; });
  }

  function host() { return document.querySelector('svg[data-mri-plate]'); }

  function inject() {
    var h = host();
    if (!h) return false;
    var which = theme();
    load(which).then(function (txt) {
      var holder = document.createElement('div');
      holder.innerHTML = txt;
      var art = holder.querySelector('svg');
      if (!art || !host()) return;
      var h2 = host();
      h2.setAttribute('viewBox', VIEWBOX);
      h2.setAttribute('preserveAspectRatio', 'xMidYMid slice');
      h2.innerHTML = art.innerHTML;
      h2.setAttribute('data-mri-plate', 'done');
      /* the page carries its own interactive markers, so the drawn ones are
         dropped here — the file keeps them for print */
      var gal = document.querySelector('.mri-index');
      if (gal) {
        gal.querySelectorAll('img[src*="art/thumbs/"]').forEach(function (im) {
          im.setAttribute('src', im.getAttribute('src').replace(/-(dark|light)\\.png/, '-' + which + '.png'));
          im.style.display = '';
        });
      }
      var drawn = h2.querySelector('#Stations');
      if (drawn) drawn.remove();
      measure(h2);
      window.MRI_PLATE.theme = which;
      /* landmarks the opening animation draws: the skyline first, then the
         trail. Tagged here so motion.js need not know the layer names. */
      var sky = h2.querySelector('#Skyline path');
      if (sky) sky.setAttribute('data-mri-outline', '');
      var route = h2.querySelector('#Route path');
      if (route) route.setAttribute('data-mri-route', '');
      relayout();
    }).catch(function (e) {
      if (window.console) console.warn('[plate]', e.message);
    });
    return true;
  }

  /* --- keeping the mountain centred ----------------------------------------
     The drawing leaves room on its right for the altitude ruler. When the
     plate is too small for the ruler (plate-enhance.js hides the label layer)
     that room stood empty and the block sat left of centre. So the viewBox is
     slid sideways until whatever is showing is centred: the block alone, or
     the block and its ruler. Measured once per drawing, while every layer is
     still on. */
  function bboxX(g) {
    try { var b = g.getBBox(); return b.width ? [b.x, b.x + b.width] : null; } catch (e) { return null; }
  }
  function union(a, b) {
    if (!a) return b;
    if (!b) return a;
    return [Math.min(a[0], b[0]), Math.max(a[1], b[1])];
  }
  function measure(h) {
    var block = union(bboxX(h.querySelector('#Ground')), bboxX(h.querySelector('#Faces')));
    var lab = h.querySelector('#Labels');
    window.MRI_PLATE.extent = { block: block, labels: union(block, lab ? bboxX(lab) : null) };
    /* the sky runs on past both edges, so a slide never uncovers a bare edge */
    var sky = h.querySelector('#Sky rect');
    if (sky) { sky.setAttribute('x', String(-AW)); sky.setAttribute('width', String(3 * AW)); }
  }
  function centre() {
    var h = document.querySelector('svg[data-mri-plate="done"]');
    var ext = window.MRI_PLATE.extent;
    if (!h || !ext || !ext.block) return;
    var lab = h.querySelector('#Labels');
    /* the labels are grown to stay legible on a wide plate, so when they show
       they are measured as they are now, not as drawn */
    var showing = lab && lab.style.display !== 'none' ? (union(ext.block, bboxX(lab)) || ext.labels) : ext.block;
    var x0 = Math.round(((showing[0] + showing[1]) / 2 - AW / 2) * 10) / 10;
    var vb = x0 + ' 0 ' + AW + ' ' + AH;
    window.MRI_PLATE.viewBox = vb;
    if (h.getAttribute('viewBox') !== vb) h.setAttribute('viewBox', vb);
  }

  /* --- putting the numbers where the terrain is ----------------------------
     The plate is injected with preserveAspectRatio="xMidYMid slice", so it
     covers its box and is cropped at the sides: a marker at "65%% of the box"
     is not at 65%% of the plate. This reproduces the browser's own slice
     transform, so every number stays welded to the ground at any size. */
  var RING = { full: 1.5, thin: 0.6 };

  function placeMarkers() {
    var plate = window.MRI_PLATE;
    var h = document.querySelector('svg[data-mri-plate="done"]');
    if (!plate || !h) return;
    var box = h.getBoundingClientRect();
    if (!box.width || !box.height) return;
    var vb = plate.viewBox.split(' ').map(Number), VX = vb[0], VY = vb[1], VW = vb[2], VH = vb[3];
    var scale = Math.max(box.width / VW, box.height / VH);
    var ox = (box.width - VW * scale) / 2 - VX * scale, oy = (box.height - VH * scale) / 2 - VY * scale;
    var placed = [];
    document.querySelectorAll('button').forEach(function (btn) {
      if (!/border-radius:\\s*50%%/.test(btn.getAttribute('style') || '')) return;
      if (!/^\\d{1,2}$/.test((btn.textContent || '').trim())) return;   /* not a station */
      var num = parseInt(btn.textContent.trim(), 10);
      var node = plate.byClimb[num] || plate.nodes[num];
      var wrap = btn.parentElement;
      if (!node || !wrap) return;
      var px = ox + (node.px / 100) * VW * scale;
      var py = oy + (node.py / 100) * VH * scale;
      wrap.style.left = px.toFixed(1) + 'px';
      wrap.style.top = py.toFixed(1) + 'px';
      var dia = plate.layout.marker;
      btn.style.width = dia + 'px';
      btn.style.height = dia + 'px';
      btn.style.inset = ((40 - dia) / 2) + 'px';
      btn.style.fontSize = (dia <= 20 ? 8.5 : 10) + 'px';
      placed.push({ btn: btn, px: px, py: py });
    });
    /* as the plate shrinks the rings close up; thin them before they blur
       into one another, so the numbers keep their contrast */
    var nearest = Infinity;
    for (var i = 0; i < placed.length; i++) {
      for (var j = i + 1; j < placed.length; j++) {
        var d = Math.hypot(placed[i].px - placed[j].px, placed[i].py - placed[j].py);
        if (d < nearest) nearest = d;
      }
    }
    if (isFinite(nearest)) {
      var dia2 = plate.layout.marker;
      var COMFORT = dia2 * 1.9, TIGHT = dia2 * 0.92;
      var t = Math.max(0, Math.min(1, (COMFORT - nearest) / (COMFORT - TIGHT)));
      var w = (RING.full + (RING.thin - RING.full) * t).toFixed(2) + 'px';
      placed.forEach(function (p) { p.btn.style.borderWidth = w; });
    }
  }

  /* the artwork runs to the window edges, so the boxes above it are taken
     full-bleed and stripped of the frame they used to carry */
  function dressFrame() {
    var h = document.querySelector('svg[data-mri-plate="done"]');
    if (!h) return;
    var frame = h.parentElement;
    if (frame) {
      frame.style.width = '100vw';
      frame.style.maxWidth = '100vw';
      frame.style.marginLeft = 'calc(50%% - 50vw)';
      frame.style.marginRight = 'calc(50%% - 50vw)';
      frame.style.aspectRatio = String(window.MRI_PLATE.layout.frame);
      frame.style.height = 'auto';
    }
    for (var n = h.parentElement, i = 0; n && i < 5; n = n.parentElement, i++) {
      if (n.tagName === 'SECTION' || n.tagName === 'BODY') break;
      n.style.setProperty('border', '0', 'important');
      n.style.setProperty('border-radius', '0', 'important');
      n.style.setProperty('background', 'transparent', 'important');
      n.style.setProperty('box-shadow', 'none', 'important');
      n.setAttribute('data-mri-undressed', String(i));
    }
  }

  var applying = false;
  function relayout() {
    if (applying) return;
    applying = true;
    try { dressFrame(); } catch (e) { /* frame gone */ }
    try { centre(); } catch (e) { /* drawing not measured yet */ }
    try { placeMarkers(); } catch (e) { /* markers not rendered yet */ }
    applying = false;
  }

  /* the host is built by the page, so wait for it rather than for the DOM */
  var t0 = Date.now();
  (function wait() {
    if (host()) { inject(); return; }
    if (Date.now() - t0 > 20000) return;
    setTimeout(wait, 60);
  })();

  window.addEventListener('resize', relayout);
  new MutationObserver(function () { relayout(); })
    .observe(document.body, { childList: true, subtree: true });

  /* a theme switch means a different drawing, not a restyle */
  new MutationObserver(function () {
    if (theme() === window.MRI_PLATE.theme) return;
    var h = document.querySelector('svg[data-mri-plate="done"]');
    if (h) { h.setAttribute('data-mri-plate', ''); inject(); }
  }).observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] });

  window.MRI_PLATE.relayout = relayout;
})();
''' % dict(W=W, H=H, table=table)

# the reading aids live in their own file, appended so the page gets one script
extra = (ROOT / 'tools' / 'plate-enhance.js')
if extra.exists():
    js = js + '\n' + extra.read_text()

(ROOT / 'plate.js').write_text(js)
print('wrote plate.js — %d stations' % len(st['stations']))
